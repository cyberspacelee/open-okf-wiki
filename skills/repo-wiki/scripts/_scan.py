# --- the test-path rule ---------------------------------------------------------------
#
# One definition of "test code" for modules, entry points, commands, build roots, terms
# and the ``tests`` fact. A path is a test path when a directory above it is a test root
# or test-support directory (outside a Maven/Gradle ``src/main`` tree), or its file name
# follows a test-runner naming convention. A name that merely contains "test" inside a
# word (latest.py, contest/, attestation.py, Testimonial.java, testing_utils.py) is not.

# camelCase test source sets and targets: integrationTest, MyAppTests, FooUnitTests.
_TEST_ROOT_CAMEL = re.compile(r"[a-z0-9](Unit|Integration|Functional)?Tests?$")
# Test roots by name, any case: tests, spec, e2e, testing; Foo.Tests, api-tests, it_test.
_TEST_ROOT = re.compile(
    r"^((tests?|specs?|__tests__|testing|e2e)"
    r"|.+[._-](unit|integration|functional|e2e)?tests?)$",
    re.IGNORECASE,
)
# Directories that hold test data or doubles: their files are test paths, but they are
# not where tests are written, so they are not reported as test directories.
_TEST_SUPPORT = re.compile(
    r"^(testdata|test[-_]data|fixtures?|__fixtures__|__mocks__|__snapshots__)$", re.IGNORECASE
)
_TEST_FILES = {"conftest.py"}
_SPEC_SUFFIXES = {".groovy", ".scala", ".kt"}  # Spock, ScalaTest/specs2, Kotest


def _test_root(part: str) -> bool:
    """A directory name that holds tests: ``tests``, ``src/test``, ``e2e``,
    ``Foo.Tests``, ``api-tests``, ``integrationTest`` (camelCase needs the capital)."""
    return bool(_TEST_ROOT.match(part) or _TEST_ROOT_CAMEL.search(part))


def _test_dir(part: str) -> bool:
    """A test root or a test-support directory (fixtures, testdata, __mocks__)."""
    return _test_root(part) or bool(_TEST_SUPPORT.match(part))


def _test_dirs(rel: str) -> list[str]:
    """Directory names of ``rel`` that can make it a test path: all of them up to a
    ``src/main`` source set (production code even in a package named ``test``)."""
    parts = rel.split("/")[:-1]
    for index in range(1, len(parts)):
        if parts[index] == "main" and parts[index - 1] == "src":
            return parts[:index]
    return parts


def is_test_path(rel: str) -> bool:
    """Whether a source-relative path is test code, test data or a test double."""
    name = rel.rsplit("/", 1)[-1]
    if name in _TEST_FILES or _test_name(name):
        return True
    return any(_test_dir(part) for part in _test_dirs(rel))


def _test_name(name: str) -> str | None:
    """The naming convention a test file name follows, as a glob, else None:
    ``test_*.py``; ``*_test.go``, ``*.test.ts``, ``*-spec.js``, ``*_spec.rb``;
    ``*Test.java``, ``*Tests.swift``, ``*IT.java`` after a lowercase letter or digit, and
    ``*Spec.scala`` likewise in Groovy, Scala and Kotlin only. A ``Test`` prefix (JUnit 3
    ``TestFoo.java``) is no rule of its own: production classes use it too (a
    ``TestResource`` endpoint); ``_test_pattern`` reports it inside test roots."""
    suffix = PurePosixPath(name).suffix
    if not suffix:
        return None
    base = name[: -len(suffix)]
    if base.startswith("test_") and len(base) > 5:
        return f"test_*{suffix}"
    for middle in ("_test", ".test", "-test", "_spec", ".spec", "-spec"):
        if base.endswith(middle) and len(base) > len(middle):
            return f"*{middle}{suffix}"
    for tail in ("Tests", "Test", "IT", "Spec"):
        if tail == "Spec" and suffix not in _SPEC_SUFFIXES:
            continue  # java.security.spec.KeySpec: Spec types are production code in Java
        if base.endswith(tail) and len(base) > len(tail):
            before = base[-len(tail) - 1]
            if before.islower() or before.isdigit():
                return f"*{tail}{suffix}"
    return None

