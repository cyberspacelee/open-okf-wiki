_TERM_DOCS = {".md", ".mdx", ".markdown", ".rst"}
_JVM_MAIN = re.compile(
    r"\bstatic\s+(?:final\s+)?void\s+main\s*\(|^\s*fun\s+main\s*\(", re.MULTILINE
)


_COMMENT_LEAD = ("#", "//", "/*", "*", "<!--", "--", ";", "'''", '"""', "@")


def _is_generated(text: str) -> bool:
    """A generated-file header: a marker on a comment line near the top (prose such
    as "pages are generated by the extension" in a doc does not count)."""
    head = text[:2048].lower()
    if not any(marker in head for marker in GENERATED_MARKERS):
        return False
    return any(
        line.lstrip().startswith(_COMMENT_LEAD) and any(m in line for m in GENERATED_MARKERS)
        for line in head.split("\n")
    )


def _term_file(rel: str) -> bool:
    """Code and doc files outside generated or vendored directories."""
    suffix = _suffix(rel)
    return (suffix in LANGUAGES or suffix in _TERM_DOCS) and not GENERATED_TOKEN.search(rel)


_PY_MAIN = re.compile(r"""^if\s+__name__\s*==\s*["']__main__["']\s*:""", re.MULTILINE)
_PEP723 = re.compile(r"^# /// script\s*$", re.MULTILINE)
_EVAL_PATH = re.compile(r"(^|[/_.-])evals?([/_.-]|$)", re.IGNORECASE)


def _pep723_command(tree: _Tree, rel: str, text: str) -> list[dict]:
    """A PEP 723 script (inline ``# /// script`` metadata) runs with ``uv run <path>``
    from the source root; test and eval scripts are kind ``test``."""
    if _suffix(rel) != ".py" or "# /// script" not in text:
        return []
    found = _PEP723.search(text)
    if not found:
        return []
    name = PurePosixPath(rel).stem
    kind = _kind(name, "")
    if kind == "other" and (_EVAL_PATH.search(rel) or is_test_path(rel)):
        kind = "test"
    command = f"uv run {shlex.quote(rel)}"
    return [{"name": name, "command": command, "kind": kind,
             "locator": tree.loc(rel, _line(text, found.start())), "cwd": command_cwd(rel, command)}]


def _main_entry(tree: _Tree, rel: str, text: str) -> list[tuple[int, str]]:
    """Programs outside tests: a JVM ``main`` method, or a Python module guarded by
    ``if __name__ == "__main__":`` at top level."""
    if "__main__" in text and _suffix(rel) == ".py" and not is_test_path(rel):
        return [(1, tree.ws(rel))] if _PY_MAIN.search(text) else []
    if "main" not in text or _suffix(rel) not in (".java", ".kt", ".scala", ".groovy"):
        return []
    if is_test_path(rel) or not _JVM_MAIN.search(text):
        return []
    # Javadoc and string examples mention main(...) too; only real code counts.
    code = _C_NOISE.sub(lambda m: re.sub(r"[^\n]", " ", m[0]), text)
    return [(1, tree.ws(rel))] if _JVM_MAIN.search(code) else []


class _Terms:
    """Term candidates across all sources; files must be added in a fixed order.

    Kinds: ``defined`` (bold definitions in docs), ``state`` (enum-like types, with
    their first members) and ``camel`` (type names used across top-level
    directories). Each kind gets a fair share of the limit so one prolific kind
    cannot crowd out the others.
    """

    RANK: ClassVar[dict[str, int]] = {"defined": 0, "state": 1, "camel": 2}
    MAX_MEMBERS = 8

    def __init__(self):
        self.df: Counter = Counter()  # capitalized token -> number of files containing it
        self.tops: dict[str, set[str]] = defaultdict(set)  # camel token -> top-level dirs
        # lower term -> (rank, term, locator); rank = (not a glossary file, not a
        # definition-list entry), so the best definition site wins
        self.defined: dict[str, tuple[tuple[bool, bool], str, str]] = {}
        self.cjk_docs: list[str] = []  # docs with CJK text, for substring counts
        self.states: dict[str, tuple[str, list[str]]] = {}  # enum -> (locator, members)
        self.camels: dict[str, str] = {}
        self.doc_words: list[frozenset[str]] = []  # lowercased words of each doc

    def add(self, tree: _Tree, rel: str, text: str) -> None:
        suffix = _suffix(rel)
        if suffix in _TERM_DOCS and _skeleton(rel):
            return  # a page template (assets/templates/en/glossary.md) is not a term source
        if is_test_path(rel):
            # Test code and fixtures define no project terms and do not count toward
            # any kind's minimum (file counts, top-level spread).
            return
        tokens = set(_CAPITALIZED.findall(text))
        self.df.update(tokens)
        top = tree.ws(rel.split("/", 1)[0] if "/" in rel else ".")
        for token in tokens:
            if _CAMEL.fullmatch(token):
                self.tops[token].add(top)
        if suffix in _TERM_DOCS:
            self.doc_words.append(frozenset(_WORD.findall(text.lower())))
            if _CJK.search(text):
                self.cjk_docs.append(text.lower())
            self._bold(tree, rel, text)
        else:
            self._definitions(tree, rel, text, suffix)

    def _bold(self, tree: _Tree, rel: str, text: str) -> None:
        glossary = _glossary_file(rel)
        for match in _BOLD_DEF.finditer(text):
            term = (match[1] or match[2]).strip().rstrip(":：").strip()
            low = term.lower()
            if (
                not re.search(r"[A-Za-z\u3400-\u9fff]", term)
                or len(term.split()) > 5
                or low in DEFINED_STOP
                or term.endswith("?")
            ):
                continue
            start = text.rfind("\n", 0, match.start()) + 1
            before = text[start:match.start()]
            if _LIST_ITEM.match(before):
                continue  # "- **Performance:** ..." is a list item heading, not a term
            rank = (not glossary, not (before.strip() == "" and _defined_after(text, match.end())))
            best = self.defined.get(low)
            if best is None or rank < best[0]:
                self.defined[low] = (rank, term, tree.loc(rel, _line(text, match.start())))

    def _definitions(self, tree: _Tree, rel: str, text: str, suffix: str) -> None:
        for match in _TYPE_DEF.finditer(text):
            name = match[1]
            if _CAMEL.fullmatch(name) and name not in self.camels:
                self.camels[name] = tree.loc(rel, _line(text, match.start(1)))
        for name, pos, members in _enums(text, suffix):
            members = [m for m in dict.fromkeys(members) if len(m) >= 2 and not m.startswith("_")]
            if len(members) >= 2 and name not in self.states:
                self.states[name] = (tree.loc(rel, _line(text, pos)), members[: self.MAX_MEMBERS])

    def _doc_count(self, low: str) -> int:
        """Docs containing every word of the term (case-insensitive); a CJK term,
        which has no spaces between words, counts its occurrences in the docs."""
        if _CJK.search(low):
            return sum(doc.count(low) for doc in self.cjk_docs)
        words = _WORD.findall(low)
        if not words:
            return 0
        return sum(1 for doc in self.doc_words if all(word in doc for word in words))

    def result(self, limit: int) -> tuple[list[dict], bool]:
        """(at most ``limit`` candidates ordered by kind then count, truncated)."""
        by_kind: dict[str, list[dict]] = {kind: [] for kind in self.RANK}
        by_kind["defined"] = [
            {"term": term, "kind": "defined", "count": max(1, self._doc_count(low)), "locator": loc}
            for low, (_, term, loc) in self.defined.items()
        ]
        rank = {low: value[0] for low, value in self.defined.items()}
        by_kind["state"] = [
            {"term": name, "kind": "state", "count": self.df[name], "locator": loc, "members": members}
            for name, (loc, members) in self.states.items()
        ]
        by_kind["camel"] = [
            {"term": name, "kind": "camel", "count": self.df[name], "locator": loc}
            for name, loc in self.camels.items()
            if self.df[name] >= 3 and len(self.tops[name]) >= 2
        ]
        seen: set[str] = set()
        for kind in self.RANK:
            # Definitions in glossary files, then definition-list entries, come first.
            ranked = sorted(by_kind[kind], key=lambda c: (
                rank.get(c["term"].lower(), (False, False)) if kind == "defined" else (False, False),
                -c["count"], c["term"]))
            unique = []
            for candidate in ranked:
                key = candidate["term"].lower()
                if key not in seen:
                    seen.add(key)
                    unique.append(candidate)
            by_kind[kind] = unique
        total = sum(len(items) for items in by_kind.values())
        share = limit // len(self.RANK)
        chosen = {kind: items[:share] for kind, items in by_kind.items()}
        room = limit - sum(len(items) for items in chosen.values())
        for kind in self.RANK:  # hand unused shares to the higher-ranked kinds first
            extra = by_kind[kind][len(chosen[kind]): len(chosen[kind]) + room]
            chosen[kind] += extra
            room -= len(extra)
        out = [candidate for kind in self.RANK for candidate in chosen[kind]]
        return out, total > len(out)


def _defined_after(text: str, end: int) -> bool:
    """Definition text follows a bold term: on the same line, or on the next line."""
    line_end = text.find("\n", end)
    rest = text[end: len(text) if line_end < 0 else line_end].strip()
    if rest:
        return True
    if line_end < 0:
        return False
    following = text[line_end + 1:].split("\n", 1)[0].strip()
    return bool(following) and not following.startswith(("#", "**", "|", "```"))


def _enums(text: str, suffix: str) -> list[tuple[str, int, list[str]]]:
    """(type name, offset of the name, member names) of enum-like state types."""
    if suffix in (".py", ".pyi"):
        return _python_enums(text)
    if suffix == ".go":
        return _go_iota_enums(text)
    if suffix in _BRACE_ENUM_SUFFIXES and "enum" in text:
        return _brace_enums(text)
    return []


def _python_enums(text: str) -> list[tuple[str, int, list[str]]]:
    out = []
    for match in _PY_ENUM.finditer(text):
        if not _PY_ENUM_BASE.search(match[3]):
            continue
        class_indent = len(match[1].expandtabs())
        body_indent = None
        members = []
        for line in text[match.end():].split("\n")[1:]:
            if not line.strip() or line.lstrip().startswith("#"):
                continue
            indent = len(line) - len(line.lstrip())
            if indent <= class_indent:
                break
            body_indent = indent if body_indent is None else body_indent
            member = re.match(r"^\s*([A-Za-z_]\w*)\s*(?::[^=]*)?=(?!=)", line)
            if indent == body_indent and member:
                members.append(member[1])
        out.append((match[2], match.start(2), members))
    return out


def _go_iota_enums(text: str) -> list[tuple[str, int, list[str]]]:
    out = []
    for match in _GO_CONST.finditer(text):
        end = text.find("\n)", match.end())
        block = text[match.end(): end if end >= 0 else len(text)]
        typed = re.search(r"^\s*(\w+)\s+([\w.]+)\s*=\s*iota\b", block, re.MULTILINE)
        if not typed:
            continue
        members = re.findall(r"^[ \t]*([A-Za-z_]\w*)\b", block, re.MULTILINE)
        out.append((typed[2].rsplit(".", 1)[-1], match.end() + typed.start(1), members))
    return out


def _brace_enums(text: str) -> list[tuple[str, int, list[str]]]:
    clean = _C_NOISE.sub(lambda m: re.sub(r"[^\n]", " ", m[0]), text)
    out = []
    for match in _BRACE_ENUM.finditer(clean):
        depth = 0
        segment_start = match.end()
        members = []
        for pos in range(match.end(), len(clean)):
            char = clean[pos]
            if char in "([{":
                depth += 1
            elif char in ")]}" and depth:
                depth -= 1
            elif depth == 0 and char in ",;}":
                segment = clean[segment_start:pos]
                member = re.match(
                    r"\s*(?:@\w+(?:\([^)]*\))?\s*|#\[[^\]]*\]\s*)*(?:case\s+)?([A-Za-z_]\w*)",
                    segment,
                )
                if member:
                    members.append(member[1])
                segment_start = pos + 1
                if char != ",":
                    break
        out.append((match[1], match.start(1), members))
    return out


# --- co-change ---------------------------------------------------------------------------------


_BUILD_FILES = {name.lower() for name in MANIFESTS} | {
    "settings.gradle", "settings.gradle.kts", "gradle.properties", "go.work",
}


def _is_manifest(path: str) -> bool:
    return _name(path).lower() in _BUILD_FILES


def _is_lock(path: str) -> bool:
    name = _name(path).lower()
    return name in LOCK_NAMES or name.endswith(".lock")


def _co_change(tree: _Tree) -> list[dict]:
    single: Counter = Counter()
    pairs: Counter = Counter()
    for files in _git.log_name_only(tree.source.path, CO_CHANGE_COMMITS):
        if len(files) > CO_CHANGE_MAX_FILES:
            continue
        keep = sorted({f for f in files if f in tree.fileset and not _is_lock(f)})
        single.update(keep)
        pairs.update(combinations(keep, 2))
    out = []
    for (a, b), support in pairs.items():
        if support < CO_CHANGE_SUPPORT or (_is_manifest(a) and _is_manifest(b)):
            # Build manifests move together on every version bump; that is release
            # mechanics, not a coupling an agent needs to know about.
            continue
        confidence = max(support / single[a], support / single[b])
        if confidence >= CO_CHANGE_CONFIDENCE:
            out.append({"a": tree.ws(a), "b": tree.ws(b), "support": support,
                        "confidence": round(confidence, 2)})
    return out
