def _glossary_file(rel: str) -> bool:
    """A file whose name says it defines terms (GLOSSARY.md, docs/terms.md, CONTEXT.md)."""
    name = _name(rel)
    return name.split(".", 1)[0].upper() in _GLOSSARY_STEMS or "glossary" in name.lower()


_SKELETON_DIRS = {"templates", "assets"}


def _skeleton(rel: str) -> bool:
    """A file under a ``templates`` or ``assets`` directory (any depth, any case): page
    skeletons and bundled copies, not project documentation."""
    return any(part.lower() in _SKELETON_DIRS for part in rel.split("/")[:-1])


def _is_doc(rel: str) -> bool:
    if _skeleton(rel):
        return False
    name = _name(rel)
    suffix = _suffix(name)
    stem = name.split(".", 1)[0].upper()
    if stem in _DOC_STEMS and (suffix in DOC_SUFFIXES or "." not in name):
        return True
    if name.lower() in ("agents.md", "claude.md", "pull_request_template.md"):
        return True
    if suffix in (".md", ".mdx"):
        return rel.startswith("docs/") or _name(_parent(rel)) == "adr"
    return False


