def _npm_scripts(text: str) -> list[tuple[str, str, int]]:
    scripts = _dict(_dict(json.loads(text)).get("scripts"))
    lines = _files.text_lines(text)
    start = _find(lines, r'^\s*"scripts"\s*:') or 1
    out = []
    for name, command in scripts.items():
        if isinstance(command, str):
            key = re.escape(json.dumps(name))
            out.append((name, command, _find(lines, rf"^\s*{key}\s*:", start - 1) or start))
    return out


_MAKE_TARGET = re.compile(r"^([A-Za-z0-9_][A-Za-z0-9_./-]*)\s*:(?!:?=)")


def _make(text: str) -> list[tuple[str, str, int]]:
    lines = _files.text_lines(text)
    out, seen = [], set()
    for index, line in enumerate(lines):
        match = _MAKE_TARGET.match(line)
        if not match or match[1] in seen:
            continue
        seen.add(match[1])
        command = None
        for following in lines[index + 1:]:
            if following.startswith("\t"):
                recipe = following.strip().lstrip("@-+").strip()
                if recipe and not recipe.startswith("#"):
                    command = recipe
                    break
            elif following.strip() and not following.lstrip().startswith("#"):
                break
        out.append((match[1], command or f"make {match[1]}", index + 1))
    return out


_JUST_RECIPE = re.compile(r"^@?([A-Za-z_][A-Za-z0-9_-]*)(?:\s+[^:]*)?:(?!=)")


def _just(text: str) -> list[tuple[str, str, int]]:
    lines = _files.text_lines(text)
    out = []
    for index, line in enumerate(lines):
        match = _JUST_RECIPE.match(line)
        if not match or match[1].startswith("_"):
            continue
        command = None
        for following in lines[index + 1:]:
            if following[:1] in (" ", "\t"):
                recipe = following.strip().lstrip("@-").strip()
                if recipe and not recipe.startswith("#"):
                    command = recipe
                    break
            elif following.strip():
                break
        out.append((match[1], command or f"just {match[1]}", index + 1))
    return out


def _taskfile(text: str) -> list[tuple[str, str, int]]:
    tasks = _dict(_dict(yaml.safe_load(text)).get("tasks"))
    lines = _files.text_lines(text)
    start = _find(lines, r"^tasks\s*:") or 1
    out = []
    for name, spec in tasks.items():
        name = str(name)
        line = _find(lines, rf"^\s+[\"']?{re.escape(name)}[\"']?\s*:", start) or start
        command = None
        if isinstance(spec, str):
            command = spec
        elif isinstance(spec, list) and spec and isinstance(spec[0], str):
            command = spec[0]
        elif isinstance(spec, dict):
            cmds = spec.get("cmds") or spec.get("cmd")
            first = cmds[0] if isinstance(cmds, list) and cmds else cmds
            if isinstance(first, dict):
                first = first.get("cmd") or (f"task {first['task']}" if first.get("task") else None)
            command = first if isinstance(first, str) else None
        out.append((name, (command or f"task {name}").strip().split("\n", 1)[0], line))
    return out


def _tox(text: str) -> list[tuple[str, str, int]]:
    lines = _files.text_lines(text)
    out = []
    for index, line in enumerate(lines):
        match = re.match(r"^\[testenv(?::([^\]]+))?\]\s*$", line.strip())
        if not match:
            continue
        name = match[1] or "testenv"
        command = None
        for offset, following in enumerate(lines[index + 1:], index + 1):
            if following.startswith("["):
                break
            cmd = re.match(r"^commands\s*=\s*(.*)$", following)
            if cmd:
                command = cmd[1].strip() or next(
                    (item.strip() for item in lines[offset + 1:] if item.strip()), None
                )
                break
        out.append((name, command or f"tox -e {name}", index + 1))
    return out


def _nox(text: str) -> list[tuple[str, str, int]]:
    lines = _files.text_lines(text)
    out = []
    for index, line in enumerate(lines):
        if not re.match(r"^\s*@nox\.session\b", line):
            continue
        override = re.search(r"name\s*=\s*['\"]([^'\"]+)['\"]", line)
        for position in range(index + 1, min(index + 10, len(lines))):
            match = re.match(r"^\s*(?:async\s+)?def\s+(\w+)", lines[position])
            if match:
                name = override[1] if override else match[1]
                out.append((name, f"nox -s {name}", position + 1))
                break
    return out


def _pyproject_tasks(text: str) -> list[tuple[str, str, int]]:
    data = tomllib.loads(text)
    tool = _dict(data.get("tool"))
    lines = _files.text_lines(text)
    out = []
    for section, table, runner in (
        ("tool.poe.tasks", _dict(_dict(tool.get("poe")).get("tasks")), "poe"),
        ("tool.pdm.scripts", _dict(_dict(tool.get("pdm")).get("scripts")), "pdm run"),
    ):
        for name, spec in table.items():
            if name.startswith("_"):
                continue
            command = _script_command(spec) or f"{runner} {name}"
            out.append((name, command, _toml_key_line(lines, section, name)))
    return out


def _script_command(spec) -> str | None:
    if isinstance(spec, dict):
        for key in ("cmd", "shell", "script", "call", "ref", "composite", "sequence"):
            if key in spec:
                spec = spec[key]
                break
    if isinstance(spec, list) and spec:
        spec = spec[0]
    if isinstance(spec, str) and spec.strip():
        return spec.strip().split("\n", 1)[0]
    return None


def _toml_key_line(lines: list[str], section: str, key: str) -> int:
    inside = False
    header = None
    for index, line in enumerate(lines):
        stripped = line.strip()
        if stripped in (f"[{section}.{key}]", f'[{section}."{key}"]'):
            return index + 1
        if stripped.startswith("["):
            inside = stripped == f"[{section}]"
            if inside:
                header = index + 1
            continue
        if inside and re.match(rf"^[\"']?{re.escape(key)}[\"']?\s*=", stripped):
            return index + 1
    return header or 1


