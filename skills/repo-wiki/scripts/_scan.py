# --- source tree at HEAD -------------------------------------------------------


class _Tree:
    """One source at HEAD: visible tracked files and blob text access."""

    def __init__(
        self,
        ws: _config.Workspace,
        source: _config.Source,
        blobs: _git.BlobReader,
        head: str | None = None,
        listing: list[str] | None = None,
    ):
        self.source = source
        self.head = head or _git.head(source.path)
        wiki = None if ws.hub else ws.wiki_rel
        if listing is None:
            listing = _git.ls_files(source.path, self.head)
        self.files = [
            path
            for path in listing
            if not (wiki and _under(path, wiki)) and not _config.is_forbidden(path)
        ]
        self.fileset = set(self.files)
        self._blobs = blobs
        self._cache: dict[str, str | None] = {}

    def ws(self, rel: str) -> str:
        """Workspace-relative path of a source-relative path ("." is the source root)."""
        if rel == ".":
            return self.source.name if self.source.prefix else "."
        return self.source.prefix + rel

    def loc(self, rel: str, line: int) -> str:
        return _config.Locator(self.ws(rel), line, line).text()  # <path>#Ln for a path with spaces

    def text(self, rel: str, cache: bool = True) -> str | None:
        """Decoded blob text; None when missing, binary or larger than 1 MiB.

        Manifests and build files are read by several extractors, so texts are
        memoized unless ``cache`` is false (the one pass over every file).
        """
        if rel in self._cache:
            return self._cache[rel]
        text = None
        if rel in self.fileset and _suffix(rel) not in BINARY_EXT:
            data = self._blobs.read(self.head, rel)
            if data is not None and len(data) <= MAX_BYTES and b"\0" not in data[:8192]:
                text = data.decode("utf-8", errors="replace")
        if cache:
            self._cache[rel] = text
        return text

    def texts(self, rels: list[str]):
        """Yield (path, text or None) like ``text`` for many paths, pipelined and uncached."""
        wanted = [rel for rel in rels if rel in self.fileset and _suffix(rel) not in BINARY_EXT]
        for rel, data in self._blobs.read_many(self.head, wanted):
            if data is None or len(data) > MAX_BYTES or b"\0" in data[:8192]:
                yield rel, None
            else:
                yield rel, data.decode("utf-8", errors="replace")


def _under(path: str, prefix: str) -> bool:
    return path == prefix or path.startswith(prefix + "/")


def _suffix(path: str) -> str:
    """Lowercase extension of the last segment, as PurePosixPath.suffix."""
    name = path.rsplit("/", 1)[-1]
    dot = name.rfind(".")
    if dot <= 0 or dot == len(name) - 1:
        return ""
    return name[dot:].lower()


def _name(path: str) -> str:
    return path.rsplit("/", 1)[-1]


def _parent(path: str) -> str:
    return path.rsplit("/", 1)[0] if "/" in path else "."


def command_cwd(rel: str, command: str) -> str:
    """Source-relative directory a command runs from, given the source-relative file
    its locator names: the source root when the command names that file by its
    source-root path (``uv run evals/run_e2e.py``, a PEP 723 script), else the
    file's directory (``npm run build`` cited at ``web/package.json`` runs in ``web``).

    ``okf scan`` records it as each command's ``cwd``; eval_canon re-derives it the
    same way for a wiki command from the file its citation names.
    """
    parent = _parent(rel)
    if parent == ".":
        return "."
    try:
        tokens = shlex.split(command)
    except ValueError:
        tokens = command.split()
    return "." if any(token.removeprefix("./") == rel for token in tokens) else parent


def _join(base: str, rel: str) -> str:
    return rel if base in ("", ".") else f"{base}/{rel}"


def _language(path: str) -> str | None:
    return LANGUAGES.get(_suffix(path))


def _dirs(files: list[str]) -> set[str]:
    dirs: set[str] = set()
    for path in files:
        parts = path.split("/")[:-1]
        for index in range(1, len(parts) + 1):
            dirs.add("/".join(parts[:index]))
    return dirs


def _line(text: str, pos: int) -> int:
    return text.count("\n", 0, pos) + 1


def _find(lines: list[str], pattern: str, start: int = 0) -> int | None:
    """1-based number of the first line at or after index ``start`` matching ``pattern``."""
    regex = re.compile(pattern)
    for index in range(max(start, 0), len(lines)):
        if regex.search(lines[index]):
            return index + 1
    return None


def _load(kind: str, text: str | None):
    if text is None:
        return None
    try:
        if kind == "json":
            return json.loads(text)
        if kind == "toml":
            return tomllib.loads(text)
        return yaml.safe_load(text)
    except (ValueError, yaml.YAMLError):
        return None


def _dict(value) -> dict:
    return value if isinstance(value, dict) else {}


def _strings(value) -> list[str]:
    return [item for item in value if isinstance(item, str)] if isinstance(value, list) else []


def _unquote(value: str) -> str:
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "'\"":
        return value[1:-1]
    return value


# --- modules --------------------------------------------------------------------


def modules(
    ws: _config.Workspace,
    heads: dict[str, str] | None = None,
    listings: dict[str, list[str]] | None = None,
) -> list[Module]:
    """Modules of every source, sorted by path (reads only manifests at HEAD).

    ``heads`` and ``listings`` (source name -> HEAD, tracked paths at HEAD) let a
    caller that already listed the sources skip a second ``git ls-tree``.
    """
    result: list[Module] = []
    for source in ws.sources:
        with _git.BlobReader(source.path) as blobs:
            tree = _Tree(
                ws, source, blobs,
                (heads or {}).get(source.name), (listings or {}).get(source.name),
            )
            found = _source_modules(tree, ws.hub)
        result += [
            Module(tree.ws(path), source.name, tree.ws(manifest) if manifest else None)
            for path, manifest in found
        ]
    return sorted(result, key=lambda module: module.path)


def _source_modules(tree: _Tree, hub: bool) -> list[tuple[str, str | None]]:
    """(source-relative module path, source-relative manifest) pairs, sorted."""
    declared = _declared(tree)
    code = [path for path in tree.files if _language(path)]
    found: dict[str, str | None] = dict(declared)
    for top in sorted({path.split("/", 1)[0] for path in code if "/" in path}):
        if top.startswith(".") or _test_dir(top) or any(_under(m, top) for m in found):
            continue  # hidden, a top-level test root, or covered by declared modules
        for path in _top_modules(tree, top, code):
            found[path] = None
    _drop_aggregators(found, code)
    if not found and (hub or any("/" not in path for path in code)):
        found["."] = None
    split = _package_modules(tree.fileset, found, code)
    attributed = {path: _attribution(tree.fileset, path, declared) for path in found}
    for path, parent in split.items():
        found[path] = None
        attributed[path] = attributed[parent]  # a package shares its build's manifest
    _drop_aggregators(found, code)
    return sorted((path, attributed[path]) for path in found)


# Top-level directories that only hold code (no build of their own): their child
# directories are the modules, as src/billing and src/payments in a src layout.
CODE_ROOTS = ("src", "lib", "app", "pkg", "internal", "packages", "source", "cmd")
# Maven/Gradle source sets: src/main and src/test are one build, not two modules.
_SOURCE_SETS = ("main",)


def _top_modules(tree: _Tree, top: str, code: list[str]) -> list[str]:
    """Modules for one top-level code directory without declared modules below it."""
    if top not in CODE_ROOTS or _own_manifest(tree.fileset, top):
        return [top]
    below = [path[len(top) + 1:] for path in code if path.startswith(top + "/")]
    children = sorted({path.split("/", 1)[0] for path in below if "/" in path})
    if any(child in _SOURCE_SETS for child in children):
        return [top]
    modules = [
        f"{top}/{child}" for child in children
        if not child.startswith(".") and not _test_dir(child)
    ]
    if any("/" not in path for path in below) or not modules:
        modules.append(top)  # code files directly in the code root
    return modules


# A package directory becomes a module of its own when its build holds at least two
# sibling packages with this many production code files each.
PACKAGE_MIN_FILES = 3
_JVM_LANG_DIRS = ("java", "kotlin", "scala", "groovy")


def _package_modules(fileset: set[str], found: dict[str, str | None], code: list[str]) -> dict[str, str]:
    """Package modules inside single builds -> the module they split.

    A JVM source set (``src/main/java``) or a Python package is followed down while
    it holds exactly one child package and no code of its own (``com/acme/shop``);
    when that base then holds two or more child packages with ``PACKAGE_MIN_FILES``
    production code files each, every such child is a module
    (``src/main/java/com/acme/shop/order``, ``src/shop/billing``). Test code stays
    with the enclosing module, and one level is split, never deeper.
    """
    owned: dict[str, list[str]] = defaultdict(list)
    for path in code:
        home = owner(path, found)
        if home is not None and not is_test_path(path):
            owned[home].append(path)
    packages = {_parent(p) for p in fileset if _name(p) == "__init__.py"}
    package_parents = {_parent(d) for d in packages}
    split: dict[str, str] = {}
    for module, files in owned.items():
        prefix = "" if module == "." else module + "/"
        bases = []
        for lang in _JVM_LANG_DIRS:
            for source_set in ("src/main/", "main/" if module.rsplit("/", 1)[-1] == "src" else None):
                if source_set and any(p.startswith(f"{prefix}{source_set}{lang}/") for p in files):
                    bases.append((f"{prefix}{source_set}{lang}", False))
        if module != "." and (module in packages or module in package_parents):
            bases.append((module, True))
        for base, python in bases:
            for child in _split_children(fileset, base, files, python):
                split[child] = module
    return split


def _split_children(fileset: set[str], base: str, files: list[str], python: bool) -> list[str]:
    below = [p for p in files if p.startswith(base + "/")]
    while True:
        rest = [p[len(base) + 1:] for p in below]
        children = {p.split("/", 1)[0] for p in rest if "/" in p}
        if len(children) != 1 or any("/" not in p for p in rest):
            break
        base = f"{base}/{children.pop()}"
        if python and f"{base}/__init__.py" not in fileset:
            return []
    counts = Counter(p[len(base) + 1:].split("/", 1)[0] for p in below if "/" in p[len(base) + 1:])
    chosen = [
        f"{base}/{child}" for child, count in sorted(counts.items())
        if count >= PACKAGE_MIN_FILES and not child.startswith((".", "_")) and not _test_dir(child)
        and (not python or f"{base}/{child}/__init__.py" in fileset)
    ]
    return chosen if len(chosen) >= 2 else []


def _attribution(fileset: set[str], path: str, declared: dict[str, str]) -> str | None:
    """The nearest manifest that owns a module: its own, else the manifest that
    declared it, else (for a code root or a directory in one) the nearest parent
    manifest, when that parent is a single build (it declares no modules)."""
    own = _own_manifest(fileset, path)
    if own or path in declared:
        return own or declared[path]
    if path == "." or path.split("/", 1)[0] not in CODE_ROOTS:
        return None
    for directory in _ancestors(_parent(path)):
        manifest = _own_manifest(fileset, directory)
        if manifest:
            if directory == ".":
                aggregates = bool(declared)
            else:
                aggregates = any(_under(m, directory) and m != directory for m in declared)
            return None if aggregates else manifest
    return None


def owner(path: str, modules) -> str | None:
    """The deepest module directory containing ``path`` (source- or workspace-relative)."""
    parts = path.split("/")[:-1]
    for index in range(len(parts), 0, -1):
        candidate = "/".join(parts[:index])
        if candidate in modules:
            return candidate
    return "." if "." in modules else None


def _drop_aggregators(found: dict[str, str | None], code: list[str]) -> None:
    """Remove modules that only aggregate nested modules (e.g. a Maven pom-packaging
    parent): they contain another module and own no code file of their own."""
    parents = {path for path in found if any(_under(other, path) and other != path for other in found)}
    if not parents:
        return
    owning = {owner(path, found) for path in code}
    for path in parents - owning:
        del found[path]


def _own_manifest(fileset: set[str], directory: str) -> str | None:
    for name in MANIFESTS:
        path = _join(directory, name)
        if path in fileset:
            return path
    return None


def _declared(tree: _Tree) -> dict[str, str]:
    """Manifest-declared module directories → the manifest that declared them."""
    fileset = tree.fileset
    dirs = _dirs(tree.files)
    found: dict[str, str] = {}

    def add(manifest: str, patterns: list[str], marker: str | None, exclude=()) -> None:
        base = _parent(manifest)
        hits: set[str] = set()
        excluded: set[str] = set()
        for pattern in patterns:
            if pattern.startswith("!"):
                excluded |= _expand(base, pattern[1:], dirs, fileset, None)
            else:
                hits |= _expand(base, pattern, dirs, fileset, marker)
        for pattern in exclude:
            excluded |= _expand(base, pattern, dirs, fileset, None)
        for path in sorted(hits - excluded):
            found.setdefault(path, manifest)

    if "package.json" in fileset:
        workspaces = _dict(_load("json", tree.text("package.json"))).get("workspaces")
        if isinstance(workspaces, dict):
            workspaces = workspaces.get("packages")
        add("package.json", _strings(workspaces), "package.json")
    if "pnpm-workspace.yaml" in fileset:
        data = _dict(_load("yaml", tree.text("pnpm-workspace.yaml")))
        add("pnpm-workspace.yaml", _strings(data.get("packages")), "package.json")
    if "Cargo.toml" in fileset:
        workspace = _dict(_dict(_load("toml", tree.text("Cargo.toml"))).get("workspace"))
        add("Cargo.toml", _strings(workspace.get("members")), "Cargo.toml",
            _strings(workspace.get("exclude")))
    if "go.work" in fileset:
        add("go.work", _go_work_uses(tree.text("go.work") or ""), "go.mod")
    for path in tree.files:
        if _name(path) == "go.mod" and "/" in path and not re.search(
            r"(^|/)(testdata|vendor|third_party)/", path
        ):
            found.setdefault(_parent(path), path)
    if "pom.xml" in fileset:
        _maven(tree, "pom.xml", found, set())
    for name in ("settings.gradle.kts", "settings.gradle"):
        if name in fileset:
            add(name, _gradle_includes(tree.text(name) or ""), None)
    if "pyproject.toml" in fileset:
        data = _dict(_load("toml", tree.text("pyproject.toml")))
        workspace = _dict(_dict(_dict(data.get("tool")).get("uv")).get("workspace"))
        add("pyproject.toml", _strings(workspace.get("members")), "pyproject.toml",
            _strings(workspace.get("exclude")))
    return found


def _norm(base: str, pattern: str) -> str | None:
    """Join a manifest-relative member path to its base; None for root or escapes."""
    pattern = pattern.strip().replace("\\", "/")
    while pattern.startswith("./"):
        pattern = pattern[2:]
    pattern = pattern.strip("/")
    if not pattern or pattern == "." or ".." in pattern.split("/"):
        return None
    return _join(base, pattern)


def _expand(base, pattern, dirs, fileset, marker) -> set[str]:
    full = _norm(base, pattern)
    if full is None:
        return set()
    if any(char in full for char in "*?["):
        hits = {d for d in dirs if _config.glob_match(full, d)}
    else:
        hits = {full} & dirs
    if marker:
        hits = {d for d in hits if f"{d}/{marker}" in fileset}
    return hits


def _go_work_uses(text: str) -> list[str]:
    uses: list[str] = []
    block = False
    for raw in _files.text_lines(text):
        line = raw.split("//", 1)[0].strip()
        if block:
            if line == ")":
                block = False
            elif line:
                uses.append(_unquote(line))
            continue
        match = re.match(r"^use\s*(.*)$", line)
        if match:
            rest = match[1].strip()
            if rest == "(":
                block = True
            elif rest:
                uses.append(_unquote(rest.strip("()")))
    return uses


def _maven(tree: _Tree, pom: str, found: dict[str, str], seen: set[str]) -> None:
    if pom in seen:
        return
    seen.add(pom)
    try:
        root = ElementTree.fromstring(tree.text(pom) or "")
    except ElementTree.ParseError:
        return
    base = _parent(pom)
    items = root.findall("./{*}modules/{*}module") + root.findall(
        "./{*}profiles/{*}profile/{*}modules/{*}module"
    )
    for item in items:
        path = _norm(base, item.text or "")
        if path and f"{path}/pom.xml" in tree.fileset:
            found.setdefault(path, pom)
            _maven(tree, f"{path}/pom.xml", found, seen)


def _gradle_includes(text: str) -> list[str]:
    text = re.sub(r"//[^\n]*|/\*.*?\*/", "", text, flags=re.DOTALL)
    names: list[str] = []
    for match in re.finditer(r"\binclude\b\s*(\()?", text):
        if match[1]:
            end = text.find(")", match.end())
            chunk = text[match.end(): end if end >= 0 else len(text)]
        else:
            chunk_lines = []
            for line in text[match.end():].split("\n"):
                chunk_lines.append(line)
                if not line.rstrip().endswith(","):
                    break
            chunk = "\n".join(chunk_lines)
        names += re.findall(r"[\"']([^\"']+)[\"']", chunk)
    return [name.strip(":").replace(":", "/") for name in names]


# --- scan ---------------------------------------------------------------------------


def scan(ws: _config.Workspace) -> dict:
    sources, mods, entries, commands, ci_files, configs = [], [], [], [], [], set()
    test_dirs: Counter = Counter()
    test_patterns: set[str] = set()
    docs: list[str] = []
    terms = _Terms()
    imports = _code.Imports()
    found_triggers: list[Trigger] = []
    named: list[tuple[str, str, str, int]] = []  # (kind, name, file, line)
    co_change: list[dict] = []
    for source in ws.sources:
        clean, dirty = _git.is_clean(source.path, [] if ws.hub else [ws.wiki_rel])
        with _git.BlobReader(source.path) as blobs:
            tree = _Tree(ws, source, blobs)
            shallow = _git.is_shallow(source.path)
            sources.append({"name": source.name, "head": tree.head, "clean": clean,
                            "dirty": [tree.ws(path) for path in dirty], "shallow": shallow})
            mods += _module_facts(tree, _source_modules(tree, ws.hub))
            entries += _entry_points(tree)
            commands += _commands(tree)
            ci_files += _ci(tree)
            configs |= _configs(tree)
            dirs, patterns = _tests(tree)
            test_dirs.update(dirs)
            test_patterns |= patterns
            docs += [tree.ws(path) for path in tree.files if _is_doc(path)]
            found_triggers += _source_triggers(tree)
            _register_packages(tree, imports)
            # The one pass that reads every hand-written code and doc blob.
            for path, text in tree.texts([p for p in tree.files if _term_file(p) or _mapper_candidate(p)]):
                if text is None or _is_generated(text):
                    continue
                if _term_file(path):
                    terms.add(tree, path, text)
                    entries += _main_entry(tree, path, text)
                    commands += _pep723_command(tree, path, text)
                if is_test_path(path):
                    continue
                if _language(path):
                    imports.add(tree.ws(path), text)
                named += [(kind, name, tree.ws(path), line) for kind, name, line in _code.resources_in(path, text)]
            co_change += _co_change(tree)

    module_paths = {m["path"] for m in mods}
    trigger_list = _trigger_facts(found_triggers, module_paths)
    per_module = Counter(t["module"] for t in trigger_list)
    for module in mods:
        module["triggers"] = per_module[module["path"]]
    deps, central = _dependency_facts(imports, module_paths)
    resources = _resource_facts(named, module_paths)
    best: dict[str, int] = {}
    for rank, path in entries:
        best[path] = min(rank, best.get(path, rank))
    entry_list = sorted(best, key=lambda p: (best[p], p.count("/"), p))
    commands.sort(key=lambda c: (c["locator"].count("/"), _loc_key(c["locator"])))
    docs = sorted(set(docs), key=lambda p: (p.count("/"), p))
    term_list, terms_truncated = terms.result(LIMITS["terms"])
    co_change.sort(key=lambda c: (-c["support"], -c["confidence"], c["a"], c["b"]))
    ranked_dirs = sorted(test_dirs, key=lambda d: (-test_dirs[d], d))[:MAX_TEST_DIRS]
    ci, ci_truncated = _bound_ci(ci_files)
    config_list, per_name = [], Counter()
    for kind, path in sorted(configs, key=lambda kp: (kp[1].count("/"), kp[1], kp[0])):
        # One file name repeated per module (tsconfig.json, spotbugs-exclude.xml)
        # says the same thing each time; keep the shallowest few.
        per_name[kind, _name(path)] += 1
        if per_name[kind, _name(path)] <= MAX_SAME_CONFIG:
            config_list.append((kind, path))

    def shown(key: str, items: list) -> list:
        return items[: LIMITS[key]]

    hints = {
        "triggers": (len(trigger_list) > LIMITS["triggers"],
                     (f"{LIMITS['triggers']} of {len(trigger_list)} trigger files shown; okf validate --json "
                     "lists every one no Workflow scope or Not covered row claims (trigger-coverage)")),
        "deps": (len(deps) > LIMITS["deps"],
                 (f"{LIMITS['deps']} of {len(deps)} module edges shown, most imports first; "
                 "read a module's imports with rg -n '^(import|from) ' <module>")),
        "central": (len(central) > LIMITS["central"],
                    f"{LIMITS['central']} of {len(central)} shared files shown, most importing modules first"),
        "resources": (len(resources) > LIMITS["resources"],
                      (f"{LIMITS['resources']} of {len(resources)} shared topics and tables shown; "
                      "rg -n '<name>' finds every use of one")),
        "entry_points": (len(entry_list) > LIMITS["entry_points"],
                         (f"{LIMITS['entry_points']} of {len(entry_list)} entry points shown, shallowest first; "
                         "triggers lists the framework entry points")),
        "terms": (terms_truncated, "more term candidates exist; read the glossary-like docs and enum types"),
        "commands": (len(commands) > LIMITS["commands"],
                     (f"{LIMITS['commands']} of {len(commands)} commands shown, shallowest first; "
                     "read the build files of the module you need")),
        "docs": (len(docs) > LIMITS["docs"],
                 f"{LIMITS['docs']} of {len(docs)} docs shown, shallowest first; git ls-files '*.md' lists all"),
        "ci": (ci_truncated, "more CI files or steps exist; read the CI directory"),
        "configs": (len(config_list) > LIMITS["configs"] or len(config_list) < len(configs),
                    "more lint, format and type configs exist (repeated per module); git ls-files lists them"),
        "co_change": (len(co_change) > MAX_CO_CHANGE,
                      f"{MAX_CO_CHANGE} of {len(co_change)} co-change pairs shown, strongest first"),
    }
    return {
        "sources": sources,
        "modules": sorted(mods, key=lambda m: m["path"]),
        "triggers": shown("triggers", trigger_list),
        "deps": shown("deps", deps),
        "central": shown("central", central),
        "resources": shown("resources", resources),
        "entry_points": shown("entry_points", entry_list),
        "commands": shown("commands", commands),
        "ci": ci,
        "configs": [
            {"kind": kind, "path": path}
            for kind, path in sorted(config_list[: LIMITS["configs"]])
        ],
        "tests": {"dirs": ranked_dirs, "patterns": sorted(test_patterns)},
        "docs": shown("docs", docs),
        "terms": term_list,
        "co_change": co_change[:MAX_CO_CHANGE],
        "truncated": {key: hint for key, (hit, hint) in hints.items() if hit},
    }


# --- triggers, dependencies and shared resources ----------------------------------------------


TRIGGER_KINDS = _code.TRIGGER_KINDS


@dataclass(frozen=True)
class Trigger:
    path: str  # workspace-relative file
    line: int
    kind: str  # one of _code.TRIGGER_KINDS


def triggers(
    ws: _config.Workspace,
    heads: dict[str, str] | None = None,
    listings: dict[str, list[str]] | None = None,
) -> list[Trigger]:
    """Every trigger at HEAD of every source: where requests, messages, schedules,
    events and commands enter production code (test and generated files excluded)."""
    found: list[Trigger] = []
    for source in ws.sources:
        with _git.BlobReader(source.path) as blobs:
            tree = _Tree(
                ws, source, blobs,
                (heads or {}).get(source.name), (listings or {}).get(source.name),
            )
            found += _source_triggers(tree)
    return sorted(found, key=lambda t: (t.path, t.line, t.kind))


def _source_triggers(tree: _Tree) -> list[Trigger]:
    hits = _git.grep_files(tree.source.path, tree.head, _code.TRIGGER_TOKENS)
    wanted = [
        path for path in tree.files
        if path in hits and _suffix(path) in _code.TRIGGER_SUFFIXES
        and not is_test_path(path) and not GENERATED_TOKEN.search(path)
    ]
    found = []
    for rel, text in tree.texts(wanted):
        if text is not None and not _is_generated(text):
            found += [Trigger(tree.ws(rel), line, kind) for line, kind in _code.triggers_in(rel, text)]
    return found


def _trigger_facts(found: list[Trigger], module_paths: set[str]) -> list[dict]:
    """One entry per trigger file: its module, kinds, trigger count and first line."""
    by_file: dict[str, list[Trigger]] = defaultdict(list)
    for trigger in found:
        by_file[trigger.path].append(trigger)
    facts = []
    for path, items in by_file.items():
        items.sort(key=lambda t: t.line)
        facts.append({
            "path": path,
            "module": owner(path, module_paths),
            "kinds": sorted({t.kind for t in items}, key=TRIGGER_KINDS.index),
            "count": len(items),
            "locator": _config.Locator(path, items[0].line, items[0].line).text(),
        })
    return sorted(facts, key=lambda f: (f["module"] or "", f["path"]))


def _register_packages(tree: _Tree, imports: _code.Imports) -> None:
    """Source root, workspace package names and Go module paths, for import resolution."""
    imports.root(tree.source.prefix)
    for rel in tree.files:
        name = _name(rel)
        if name == "package.json" and not is_test_path(rel) and not GENERATED_TOKEN.search(rel):
            package = _dict(_load("json", tree.text(rel))).get("name")
            if isinstance(package, str) and package:
                imports.package(package, tree.ws(rel))
        elif name == "go.mod" and not re.search(r"(^|/)(testdata|vendor|third_party)/", rel):
            found = re.search(r"^module\s+(\S+)", tree.text(rel) or "", re.MULTILINE)
            if found:
                imports.go_module(_unquote(found[1]), tree.ws(_parent(rel)))


def _mapper_candidate(rel: str) -> bool:
    """An XML file that may be a MyBatis mapper (its SQL names tables)."""
    return _suffix(rel) == ".xml" and not is_test_path(rel) and not GENERATED_TOKEN.search(rel)


def _dependency_facts(imports: _code.Imports, module_paths: set[str]) -> tuple[list[dict], list[dict]]:
    """Module edges (importing module -> imported module) and the files most modules import."""
    edges: dict[tuple[str, str], set[tuple[str, int]]] = defaultdict(set)
    importers: dict[str, set[str]] = defaultdict(set)
    statements: Counter = Counter()
    for path, line, target in imports.edges():
        source, dest = owner(path, module_paths), owner(target, module_paths)
        if source is None or dest is None or source == dest:
            continue
        edges[source, dest].add((path, line))
        importers[target].add(source)
        statements[target] += 1
    deps = []
    for (source, dest), sites in edges.items():
        path, line = min(sites)
        deps.append({
            "from": source, "to": dest, "count": len(sites),
            "locator": _config.Locator(path, line, line).text(),
            "mutual": (dest, source) in edges,
        })
    deps.sort(key=lambda d: (-d["count"], d["from"], d["to"]))
    central = [
        {"path": target, "module": owner(target, module_paths), "modules": len(users),
         "imports": statements[target]}
        for target, users in importers.items() if len(users) >= 2
    ]
    central.sort(key=lambda c: (-c["modules"], -c["imports"], c["path"]))
    return deps, central


def _resource_facts(named: list[tuple[str, str, str, int]], module_paths: set[str]) -> list[dict]:
    """Topics and tables named in two or more modules, with the first site per module."""
    sites: dict[tuple[str, str], dict[str, tuple[str, int]]] = defaultdict(dict)
    for kind, name, path, line in sorted(named, key=lambda n: (n[2], n[3])):
        module = owner(path, module_paths)
        if module is not None:
            sites[kind, name].setdefault(module, (path, line))
    out = []
    for (kind, name), by_module in sites.items():
        if len(by_module) < 2:
            continue
        out.append({
            "kind": kind, "name": name, "modules": sorted(by_module),
            "locators": [_config.Locator(p, n, n).text() for _, (p, n) in sorted(by_module.items())][:6],
        })
    return sorted(out, key=lambda r: (-len(r["modules"]), r["kind"], r["name"]))


def _bound_ci(files: list[dict]) -> tuple[list[dict], bool]:
    """At most ``ci_files`` files and ``ci_steps`` steps, shallowest files first."""
    files = sorted(files, key=lambda f: (f["file"].count("/"), f["file"]))
    out, budget, truncated = [], LIMITS["ci_steps"], False
    for item in files:
        if len(out) == LIMITS["ci_files"] or (budget == 0 and item["steps"]):
            truncated = True
            break
        steps = item["steps"][:budget]
        truncated |= len(steps) < len(item["steps"])
        budget -= len(steps)
        out.append({"file": item["file"], "steps": steps})
    return sorted(out, key=lambda f: f["file"]), truncated


def _loc_key(locator: str) -> tuple[str, int]:
    path, _, line = locator.partition("#L")
    return path.strip("<>"), int(line or 0)


def _module_facts(tree: _Tree, found: list[tuple[str, str | None]]) -> list[dict]:
    stats = {path: [0, Counter()] for path, _ in found}
    for rel in tree.files:
        home = owner(rel, stats)
        if home is None:
            continue
        stats[home][0] += 1
        language = _language(rel)
        if language:
            stats[home][1][language] += 1
    return [
        {
            "path": tree.ws(path),
            "source": tree.source.name,
            "manifest": tree.ws(manifest) if manifest else None,
            "files": stats[path][0],
            "languages": dict(sorted(stats[path][1].items(), key=lambda kv: (-kv[1], kv[0]))),
        }
        for path, manifest in found
    ]


# --- entry points ------------------------------------------------------------------


def _entry_points(tree: _Tree) -> list[tuple[int, str]]:
    """(rank, workspace path): 0 declared by a manifest, 1 conventional code, 2 specs."""
    out: list[tuple[int, str]] = []
    for rel in tree.files:
        name = _name(rel)
        low = name.lower()
        if name == "pyproject.toml":
            out += [(0, tree.ws(p)) for p in _pyproject_entries(tree, rel)]
        elif name == "package.json":
            out += [(0, tree.ws(p)) for p in _package_entries(tree, rel)]
        if is_test_path(rel) or GENERATED_TOKEN.search(rel):
            continue
        if low in ENTRY_BASENAMES or low.endswith(("application.java", "application.kt")):
            out.append((1, tree.ws(rel)))
        elif low in ENTRY_SPECS:
            out.append((2, tree.ws(rel)))
    return out


def _pyproject_entries(tree: _Tree, rel: str) -> list[str]:
    data = _dict(_load("toml", tree.text(rel)))
    project = _dict(data.get("project"))
    targets = list(_dict(project.get("scripts")).values())
    targets += list(_dict(project.get("gui-scripts")).values())
    targets += list(_dict(_dict(_dict(data.get("tool")).get("poetry")).get("scripts")).values())
    base = _parent(rel)
    out = []
    for target in targets:
        if not isinstance(target, str):
            continue
        module = target.split(":", 1)[0].strip().replace(".", "/")
        for candidate in (f"{module}.py", f"{module}/__main__.py", f"{module}/__init__.py",
                          f"src/{module}.py", f"src/{module}/__init__.py"):
            path = _join(base, candidate)
            if path in tree.fileset:
                out.append(path)
                break
    return out


def _package_entries(tree: _Tree, rel: str) -> list[str]:
    data = _dict(_load("json", tree.text(rel)))
    values = [data.get("main")]
    binary = data.get("bin")
    values += list(binary.values()) if isinstance(binary, dict) else [binary]
    base = _parent(rel)
    out = []
    for value in values:
        if isinstance(value, str) and (path := _norm(base, value)) in tree.fileset:
            out.append(path)
    return out


# --- commands -------------------------------------------------------------------------


def _commands(tree: _Tree) -> list[dict]:
    """Declared commands (scripts, targets, tasks) plus the conventional commands of
    each build tool. A command runs from its ``cwd`` (see command_cwd): the directory
    of the file its locator names.
    A conventional command already declared in that directory is left out."""
    out: list[dict] = []
    seen: set[tuple[str, str]] = set()
    for rel in sorted(tree.files, key=lambda p: (p.count("/"), p)):
        parser = COMMAND_FILES.get(_name(rel).lower())
        if parser is None:
            continue
        text = tree.text(rel)
        if text is None:
            continue
        try:
            found = parser(text)
        except (ValueError, yaml.YAMLError, AttributeError, TypeError):
            found = []
        runner = _js_runner(tree, rel, text) if _name(rel) == "package.json" else None
        for name, command, line in sorted(found, key=lambda item: (item[2], item[0])):
            kind = _kind(name, command)
            if runner:  # the script body is at the locator; the command is how to run it
                command = f"{runner} run {name}"
            seen.add((_parent(rel), command))
            out.append({"name": name, "command": command, "kind": kind, "locator": tree.loc(rel, line),
                        "cwd": command_cwd(rel, command)})
    for detect in BUILD_TOOLS:
        for rel, line, name, command, kind in detect(tree):
            if (_parent(rel), command) not in seen:
                seen.add((_parent(rel), command))
                out.append({"name": name, "command": command, "kind": kind,
                            "locator": tree.loc(rel, line), "cwd": command_cwd(rel, command)})
    return out


# Command kinds, checked in this order against the words of the name, then the command.
COMMAND_KINDS = (
    ("format", {"fmt", "format", "formatting", "prettier", "black", "isort", "spotless",
                "gofmt", "rustfmt", "scalafmt"}),
    ("typecheck", {"typecheck", "types", "typing", "mypy", "pyright", "tsc"}),
    ("lint", {"lint", "linter", "linting", "eslint", "ruff", "flake8", "pylint", "clippy",
              "vet", "checkstyle", "spotbugs", "pmd", "golangci", "rubocop", "stylelint",
              "biome", "detekt", "ktlint"}),
    ("test", {"test", "tests", "testing", "pytest", "jest", "vitest", "mocha", "karma",
              "ctest", "spec", "specs", "e2e", "integration", "coverage", "cov", "unittest",
              "playwright", "cypress"}),
    ("build", {"build", "compile", "package", "bundle", "dist", "assemble"}),
)
_NAME_ONLY_TEST = {"it", "its"}  # integration-test task names; too common as a word


def _kind(name: str, command: str) -> str:
    """build, test, lint, format, typecheck or other, from the name first."""
    for text, is_name in ((name, True), (command, False)):
        low = re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", text).lower()  # integrationTest
        words = set(re.findall(r"[a-z0-9]+", low))
        if "typecheck" in re.sub(r"[^a-z]", "", low):
            words.add("typecheck")
        if is_name:
            words |= {"test"} if words & _NAME_ONLY_TEST else set()
        words |= {"test" for word in words if word.startswith("test")}
        for kind, vocabulary in COMMAND_KINDS:
            if words & vocabulary:
                return kind
    return "other"


_JS_LOCKS = (
    ("pnpm-lock.yaml", "pnpm"), ("yarn.lock", "yarn"), ("bun.lockb", "bun"), ("bun.lock", "bun"),
    ("package-lock.json", "npm"), ("npm-shrinkwrap.json", "npm"),
)


def _js_runner(tree: _Tree, rel: str, text: str) -> str:
    """The package manager of a package.json: ``packageManager``, else the nearest lock."""
    declared = _dict(_load("json", text)).get("packageManager")
    if isinstance(declared, str) and declared.split("@", 1)[0] in ("npm", "pnpm", "yarn", "bun"):
        return declared.split("@", 1)[0]
    for directory in _ancestors(_parent(rel)):
        for lock, runner in _JS_LOCKS:
            if _join(directory, lock) in tree.fileset:
                return runner
    return "npm"


def _ancestors(directory: str):
    """``directory`` and each parent up to the source root "."."""
    while True:
        yield directory
        if directory == ".":
            return
        directory = _parent(directory)


# --- build-tool commands ----------------------------------------------------------------
#
# Each detector returns (source-relative file, line, name, command, kind). Build roots are
# the outermost build files: a Maven reactor child or a Cargo workspace member runs from
# its root. Fixture, example and generated build files are no build roots.

_FIXTURE = re.compile(r"(^|/)(src|examples?|samples?|node_modules|vendor|buildSrc)/")


def _fixture(rel: str) -> bool:
    return bool(_FIXTURE.search(rel) or is_test_path(rel) or GENERATED_TOKEN.search(rel))


def _build_roots(tree: _Tree, rank) -> list[tuple[str, str]]:
    """(directory, file) of the outermost build files, shallowest first.

    ``rank(name)`` orders the build file names of one directory (lower wins; None is
    not a build file); a directory below another build directory is left out.
    """
    best: dict[str, tuple[int, str]] = {}
    for rel in tree.files:
        order = rank(_name(rel))
        if order is None or _fixture(rel):
            continue
        directory = _parent(rel)
        if directory not in best or (order, rel) < best[directory]:
            best[directory] = (order, rel)
    out = []
    for directory in sorted(best, key=lambda d: (-1 if d == "." else d.count("/"), d)):
        if directory != "." and any(a in best for a in _ancestors(_parent(directory))):
            continue
        out.append((directory, best[directory][1]))
    return out


def _named(*names: str):
    return lambda name: names.index(name) if name in names else None


def _lines(tree: _Tree, rel: str) -> list[str]:
    return _files.text_lines(tree.text(rel) or "")


def _outer_tag_line(lines: list[str], tag: str) -> int | None:
    """The least indented ``<tag>`` line (a project's own, not a profile's)."""
    found = [(len(line) - len(line.lstrip()), index + 1)
             for index, line in enumerate(lines) if re.match(rf"^\s*<{tag}>", line)]
    return min(found)[1] if found else None


MAX_PROFILES = 3
MAVEN_PLUGINS = (  # (artifactId, goal, kind)
    ("spotless-maven-plugin", "spotless:check", "format"),
    ("maven-checkstyle-plugin", "checkstyle:check", "lint"),
    ("spotbugs-maven-plugin", "spotbugs:check", "lint"),
    ("maven-pmd-plugin", "pmd:check", "lint"),
)


def _maven_commands(tree: _Tree) -> list[tuple]:
    out = []
    for base, pom in _maven_roots(tree):
        text = tree.text(pom)
        if text is None:
            continue
        lines = _files.text_lines(text)
        mvn = "./mvnw" if _join(base, "mvnw") in tree.fileset else "mvn"
        line = _outer_tag_line(lines, "build") or _find(lines, r"<project\b") or 1
        out += [(pom, line, "test", f"{mvn} -q test", "test"),
                (pom, line, "verify", f"{mvn} -q verify", "build")]
        try:
            root = ElementTree.fromstring(text)
        except ElementTree.ParseError:
            root = None
        ids = [] if root is None else [
            (item.text or "").strip() for item in root.findall("./{*}profiles/{*}profile/{*}id")
        ]
        ids = [pid for pid in ids if re.fullmatch(r"[\w.-]+", pid)]
        if len(ids) <= MAX_PROFILES:
            start = (_find(lines, r"<profiles>") or 1) - 1
            for pid in ids:
                at = _find(lines, rf"<id>\s*{re.escape(pid)}\s*</id>", start) or line
                out.append((pom, at, f"verify -P{pid}", f"{mvn} -q verify -P{pid}", "build"))
        for artifact, goal, kind in MAVEN_PLUGINS:
            at = _find(lines, rf"<artifactId>\s*{re.escape(artifact)}\s*</artifactId>")
            if at:
                out.append((pom, at, goal, f"{mvn} -q {goal}", kind))
    return out


def _maven_roots(tree: _Tree) -> list[tuple[str, str]]:
    """(directory, pom) of every pom no other pom lists in its (or a profile's) modules."""
    poms = [rel for rel in tree.files if _name(rel) == "pom.xml" and not _fixture(rel)]
    children: set[str] = set()
    for pom in poms:
        try:
            root = ElementTree.fromstring(tree.text(pom) or "")
        except ElementTree.ParseError:
            continue
        items = root.findall("./{*}modules/{*}module") + root.findall(
            "./{*}profiles/{*}profile/{*}modules/{*}module")
        for item in items:
            path = _norm(_parent(pom), item.text or "")
            if path:
                children.add(_join(path, "pom.xml"))
    roots = [pom for pom in poms if pom not in children]
    return [(_parent(pom), pom) for pom in sorted(roots, key=lambda p: (p.count("/"), p))]


GRADLE_FILES = ("settings.gradle.kts", "settings.gradle", "build.gradle.kts", "build.gradle")
_GRADLE_TASK = re.compile(
    r"\btasks\s*\.\s*(?:register|create)\s*(?:<[^>\n]*>)?\s*\(\s*[\"']([\w.-]+)[\"']"
    r"|^\s*task\b\s*\(?\s*[\"']?([A-Za-z_][\w-]*)\b"
    r"|\bval\s+(\w+)\s+by\s+tasks\s*\.\s*(?:registering|creating)\b",
    re.MULTILINE,
)
_GRADLE_COMMENT = re.compile(r"(?<![:\"'])//[^\n]*|/\*.*?\*/", re.DOTALL)
GRADLE_PLUGINS = (  # (plugin pattern, task, kind)
    (r"com\.diffplug\.spotless|\bspotless\s*\{", "spotlessCheck", "format"),
    (r"[\"']checkstyle[\"']|\bcheckstyle\s*\{", "checkstyleMain", "lint"),
)


def _gradle_commands(tree: _Tree) -> list[tuple]:
    out = []
    roots = _build_roots(tree, _named(*GRADLE_FILES))
    for base, rel in roots:
        wrapper = "./gradlew" if _join(base, "gradlew") in tree.fileset else "gradle"
        lines = _lines(tree, rel)
        line = _find(lines, r"rootProject\.name|^\s*plugins\s*\{") or 1
        out += [(rel, line, "test", f"{wrapper} test", "test"),
                (rel, line, "build", f"{wrapper} build", "build")]
        for name in GRADLE_FILES[2:]:
            build = _join(base, name)
            text = tree.text(build) if build in tree.fileset else None
            for pattern, task, kind in GRADLE_PLUGINS if text else ():
                at = _find(_files.text_lines(text), pattern)
                if at:
                    out.append((build, at, task, f"{wrapper} {task}", kind))
    projects: dict[str, str] = {}  # project directory -> its build root
    for base, _ in roots:
        projects[base] = base
        for name in GRADLE_FILES[:2]:
            settings = _join(base, name)
            if settings in tree.fileset:
                for include in _gradle_includes(tree.text(settings) or ""):
                    if (path := _norm(base, include)):
                        projects.setdefault(path, base)
    for rel in tree.files:
        directory = _parent(rel)
        # build.gradle(.kts), or a script named after its project directory (a settings
        # file may set buildFileName, as Spring Framework's spring-core/spring-core.gradle)
        own = {f"{_name(directory)}.gradle", f"{_name(directory)}.gradle.kts"}
        if (_name(rel) not in GRADLE_FILES[2:] and _name(rel) not in own) or _fixture(rel):
            continue
        base = projects.get(directory)
        if base is None:
            continue  # not a project of any build
        depth = 0 if directory == base else directory.count("/") + 1 - (
            0 if base == "." else base.count("/") + 1)
        wrapper = ("./" if depth == 0 else "../" * depth) + "gradlew"
        if _join(base, "gradlew") not in tree.fileset:
            wrapper = "gradle"
        text = _GRADLE_COMMENT.sub(lambda m: re.sub(r"[^\n]", " ", m[0]), tree.text(rel) or "")
        for match in _GRADLE_TASK.finditer(text):
            name = match[1] or match[2] or match[3]
            out.append((rel, _line(text, match.start()), name, f"{wrapper} {name}",
                        _kind(name, "")))
    return out


def _cargo_commands(tree: _Tree) -> list[tuple]:
    out = []
    for base, rel in _build_roots(tree, _named("Cargo.toml")):
        lines = _lines(tree, rel)
        line = _find(lines, r"^\s*\[(workspace|package)\]") or 1
        out += [(rel, line, "build", "cargo build", "build"),
                (rel, line, "test", "cargo test", "test")]
        clippy = next((_join(base, n) for n in ("clippy.toml", ".clippy.toml")
                       if _join(base, n) in tree.fileset), None)
        lints = _find(lines, r"^\s*\[(workspace\.)?lints\.clippy\]|^\s*clippy\s*=|^\s*clippy\.")
        if clippy or lints:
            out.append((clippy or rel, 1 if clippy else lints, "clippy",
                        "cargo clippy --all-targets", "lint"))
        rustfmt = next((_join(base, n) for n in ("rustfmt.toml", ".rustfmt.toml")
                        if _join(base, n) in tree.fileset), None)
        if rustfmt:
            out.append((rustfmt, 1, "fmt", "cargo fmt --check", "format"))
    return out


_GOLANGCI = (".golangci.yml", ".golangci.yaml", ".golangci.toml", ".golangci.json")


def _go_commands(tree: _Tree) -> list[tuple]:
    """Every Go module runs its own ``./...``; nested modules are not covered by a parent."""
    out = []
    for rel in tree.files:
        if _name(rel) != "go.mod" or _fixture(rel):
            continue
        base = _parent(rel)
        line = _find(_lines(tree, rel), r"^\s*module\b") or 1
        out += [(rel, line, "test", "go test ./...", "test"),
                (rel, line, "vet", "go vet ./...", "lint")]
        config = next((_join(base, n) for n in _GOLANGCI if _join(base, n) in tree.fileset), None)
        if config:
            out.append((config, 1, "golangci-lint", "golangci-lint run", "lint"))
    return out


PY_TOOLS = {  # tool -> (command, kind)
    "pytest": ("pytest", "test"), "ruff": ("ruff check .", "lint"),
    "mypy": ("mypy .", "typecheck"), "pyright": ("pyright", "typecheck"),
    "black": ("black --check .", "format"), "isort": ("isort --check-only .", "format"),
    "flake8": ("flake8", "lint"),
}
_PY_LOCKS = (("uv.lock", "uv run "), ("poetry.lock", "poetry run "), ("pdm.lock", "pdm run "))
_INI_TOOLS = (  # (section regex, tool) in setup.cfg, tox.ini, pytest.ini, mypy.ini, .flake8
    (re.compile(r"^(tool:pytest|pytest)$"), "pytest"),
    (re.compile(r"^mypy$"), "mypy"),
    (re.compile(r"^flake8$"), "flake8"),
    (re.compile(r"^isort$|^tool:isort$"), "isort"),
)
_PY_CONFIG_FILES = {"pyproject.toml", "ruff.toml", ".ruff.toml", "pytest.ini", "mypy.ini",
                    ".mypy.ini", "pyrightconfig.json", ".flake8", "setup.cfg", "tox.ini"}


def _python_commands(tree: _Tree) -> list[tuple]:
    """Configured Python tools, run through uv, poetry or pdm when their lock is present."""
    out = []
    for rel in tree.files:
        name = _name(rel)
        if name not in _PY_CONFIG_FILES or _fixture(rel):
            continue
        text = tree.text(rel)
        if text is None:
            continue
        lines = _files.text_lines(text)
        found: dict[str, int] = {}  # tool -> line
        extra: list[tuple] = []
        if name == "pyproject.toml":
            found, extra = _pyproject_tools(rel, text, lines)
        elif name in ("ruff.toml", ".ruff.toml"):
            found["ruff"] = 1
            if (at := _find(lines, r"^\s*\[format\]")):
                extra.append((rel, at, "ruff format", "ruff format --check .", "format"))
        elif name == "pyrightconfig.json":
            found["pyright"] = 1
        else:
            for index, line in enumerate(lines):
                section = re.match(r"^\[([^\]]+)\]\s*$", line.strip())
                for regex, tool in _INI_TOOLS if section else ():
                    if regex.match(section[1].strip()) and tool not in found:
                        found[tool] = index + 1
            if name == ".flake8":
                found.setdefault("flake8", 1)
        if "mypy" in found and re.search(r"^\s*files\s*=", text, re.MULTILINE):
            mypy = "mypy"
        else:
            mypy = "mypy ."
        prefix = next((p for d in _ancestors(_parent(rel)) for lock, p in _PY_LOCKS
                       if _join(d, lock) in tree.fileset), "")
        for tool, line in sorted(found.items(), key=lambda kv: (kv[1], kv[0])):
            command, kind = PY_TOOLS[tool]
            command = mypy if tool == "mypy" else command
            out.append((rel, line, tool, prefix + command, kind))
        out += [(r, at, n, prefix + c if n == "ruff format" else c, k) for r, at, n, c, k in extra]
    return out


def _pyproject_tools(rel: str, text: str, lines: list[str]) -> tuple[dict[str, int], list[tuple]]:
    data = _dict(_load("toml", text))
    tool = _dict(data.get("tool"))
    found: dict[str, int] = {}
    for key in PY_TOOLS:
        if key in tool:
            found[key] = _find(lines, rf"^\s*\[tool\.{key}[.\]]") or 1
    for dep in _dev_dependencies(data):
        if dep in PY_TOOLS and dep not in found:
            found[dep] = _find(lines, rf"[\"']{re.escape(dep)}(?![\w-])|^\s*{re.escape(dep)}\s*=") or 1
    extra = []
    ruff = _dict(tool.get("ruff"))
    if "format" in ruff:
        at = _find(lines, r"^\s*\[tool\.ruff\.format\]") or found.get("ruff", 1)
        extra.append((rel, at, "ruff format", "ruff format --check .", "format"))
    for env in _dict(_dict(tool.get("tox")).get("env")):
        at = _find(lines, rf"^\s*\[tool\.tox\.env\.[\"']?{re.escape(env)}[\"']?\]") or 1
        extra.append((rel, at, env, f"tox -e {env}", _kind(env, "")))
    return found, extra


def _dev_dependencies(data: dict) -> set[str]:
    """Distribution names in dependency groups, extras and dev dependency tables."""
    specs: list = []
    for group in _dict(data.get("dependency-groups")).values():
        specs += _strings(group)
    for extra in _dict(_dict(data.get("project")).get("optional-dependencies")).values():
        specs += _strings(extra)
    tool = _dict(data.get("tool"))
    specs += _strings(_dict(tool.get("uv")).get("dev-dependencies"))
    poetry = _dict(tool.get("poetry"))
    specs += list(_dict(poetry.get("dev-dependencies")))
    for group in _dict(poetry.get("group")).values():
        specs += list(_dict(_dict(group).get("dependencies")))
    names = set()
    for spec in specs:
        match = re.match(r"\s*([A-Za-z0-9][A-Za-z0-9._-]*)", spec)
        if match:
            names.add(match[1].lower().replace("_", "-"))
    return names


def _dotnet_commands(tree: _Tree) -> list[tuple]:
    """Each solution builds and tests its projects; without one, each outermost project."""
    out = []
    solutions = [rel for rel in tree.files if _suffix(rel) in (".sln", ".slnx") and not _fixture(rel)]
    for rel in solutions:
        line = _find(_lines(tree, rel), r"^Project\(|<Project\b") or 1
        out += [(rel, line, "build", f"dotnet build {_name(rel)}", "build"),
                (rel, line, "test", f"dotnet test {_name(rel)}", "test")]
    if not solutions:
        for _, rel in _build_roots(tree, _dotnet_project):
            out += [(rel, 1, "build", "dotnet build", "build"), (rel, 1, "test", "dotnet test", "test")]
    return out


def _dotnet_project(name: str) -> int | None:
    return 0 if _suffix(name) in (".csproj", ".fsproj", ".vbproj") else None


def _cmake_commands(tree: _Tree) -> list[tuple]:
    out = []
    for _, rel in _build_roots(tree, _named("CMakeLists.txt")):
        lines = _lines(tree, rel)
        line = _find(lines, r"^\s*project\s*\(") or 1
        out += [(rel, line, "configure", "cmake -S . -B build", "build"),
                (rel, line, "build", "cmake --build build", "build")]
        testing = _find(lines, r"^\s*(enable_testing\s*\(|include\s*\(\s*CTest\b)")
        if testing:
            out.append((rel, testing, "ctest", "ctest --test-dir build", "test"))
    return out


