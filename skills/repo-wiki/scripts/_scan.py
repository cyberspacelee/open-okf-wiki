# --- CI ---------------------------------------------------------------------------------


def _ci(tree: _Tree) -> list[dict]:
    out = []
    for rel in tree.files:
        name = _name(rel)
        if (rel.startswith(".github/workflows/") and rel.count("/") == 2
                and _suffix(rel) in (".yml", ".yaml")):
            parser = _github_steps
        elif rel == ".gitlab-ci.yml":
            parser = _gitlab_steps
        elif name == "Jenkinsfile":
            parser = _jenkins_steps
        else:
            continue
        text = tree.text(rel)
        if text is None:
            continue
        steps = [
            {"name": step_name, "run": run, "locator": tree.loc(rel, line)}
            for step_name, run, line in parser(text)
        ]
        out.append({"file": tree.ws(rel), "steps": steps})
    return out


_YAML_ONLY_BREAKS = re.compile(r"\r(?!\n)|[\x85\u2028\u2029]")


def _compose(text: str):
    # YAML also breaks lines at a lone CR, NEL, U+2028 and U+2029; git does not.
    # Blank them so node line numbers (locators) agree with git's line count.
    text = _YAML_ONLY_BREAKS.sub(" ", text)
    try:
        return yaml.compose(text, Loader=yaml.SafeLoader)
    except yaml.YAMLError:
        return None


def _pairs(node) -> list[tuple[str, int, object]]:
    """(key, 1-based key line, value node) of a YAML mapping node."""
    if not isinstance(node, yaml.MappingNode):
        return []
    return [
        (key.value, key.start_mark.line + 1, value)
        for key, value in node.value
        if isinstance(key, yaml.ScalarNode)
    ]


def _get(node, key: str):
    return next((value for name, _, value in _pairs(node) if name == key), None)


_SHELL_NOISE = re.compile(r"^(?:#|set\s+[-+]|shopt\s)")
MAX_RUN = 200


def _first_line(value: str) -> str:
    """The first command of a shell script: comments and ``set -e`` style lines
    skipped, backslash continuations joined, at most MAX_RUN characters."""
    lines = [line.strip() for line in value.splitlines()]
    for index, line in enumerate(lines):
        if not line or _SHELL_NOISE.match(line):
            continue
        parts = [line]
        while parts[-1].endswith("\\") and index + 1 < len(lines):
            parts[-1] = parts[-1][:-1].rstrip()
            index += 1
            parts.append(lines[index])
        command = " ".join(part for part in parts if part)
        return command if len(command) <= MAX_RUN else command[: MAX_RUN - 1] + "…"
    return ""


def _github_steps(text: str) -> list[tuple[str, str, int]]:
    out = []
    for job, _, spec in _pairs(_get(_compose(text), "jobs")):
        uses = next(((line, value) for key, line, value in _pairs(spec) if key == "uses"), None)
        if uses and isinstance(uses[1], yaml.ScalarNode):
            # A reusable workflow: the real steps live in another repository.
            out.append((job, f"uses {uses[1].value}", uses[0]))
            continue
        steps = _get(spec, "steps")
        for step in steps.value if isinstance(steps, yaml.SequenceNode) else []:
            fields = {key: (line, value) for key, line, value in _pairs(step)}
            run = fields.get("run")
            if run is None or not isinstance(run[1], yaml.ScalarNode):
                continue
            name = fields.get("name")
            label = name[1].value if name and isinstance(name[1], yaml.ScalarNode) else job
            out.append((label, _first_line(run[1].value), run[0]))
    return out


_GITLAB_RESERVED = {
    "stages", "variables", "default", "include", "workflow", "image", "services",
    "before_script", "after_script", "cache", "pages",
}


def _gitlab_steps(text: str) -> list[tuple[str, str, int]]:
    out = []
    for job, _, spec in _pairs(_compose(text)):
        if job.startswith(".") or job in _GITLAB_RESERVED:
            continue
        stack = [_get(spec, "script")]
        while stack:
            node = stack.pop(0)
            if isinstance(node, yaml.ScalarNode) and node.value.strip():
                out.append((job, _first_line(node.value), node.start_mark.line + 1))
            elif isinstance(node, yaml.SequenceNode) and node.tag != "!reference":
                stack = list(node.value) + stack
    return out


def _jenkins_steps(text: str) -> list[tuple[str, str, int]]:
    lines = _files.text_lines(text)
    steps = []
    stage = None
    for index, line in enumerate(lines):
        named = re.search(r"\bstage\s*\(\s*['\"]([^'\"]+)['\"]", line)
        if named:
            stage = named[1]
        match = re.search(r"\bsh\s*\(?\s*(?:script\s*:\s*)?('''|\"\"\"|'|\")(.*)$", line)
        if not match:
            continue
        quote, rest = match[1], match[2]
        if len(quote) == 3:
            run = rest.split(quote, 1)[0].strip() or next(
                (item.strip() for item in lines[index + 1:] if item.strip()), ""
            )
        else:
            run = rest.split(quote, 1)[0].strip()
        steps.append((stage or "sh", run, index + 1))
    return steps


# --- configs, tests, docs -----------------------------------------------------------------


def _configs(tree: _Tree) -> set[tuple[str, str]]:
    out: set[tuple[str, str]] = set()
    for rel in tree.files:
        name = _name(rel)
        low = name.lower()
        for kind, regex in _CONFIG_REGEX:
            if regex.match(low):
                out.add((kind, tree.ws(rel)))
        if rel.startswith(".husky/"):
            out.add(("precommit", tree.ws(rel)))
        if rel in (".vscode/settings.json", ".vscode/extensions.json"):
            out.add(("editor", tree.ws(rel)))
        kinds: set[str] = set()
        if name == "pyproject.toml":
            tool = _dict(_dict(_load("toml", tree.text(rel))).get("tool"))
            kinds = {PYPROJECT_TOOLS[key] for key in tool if key in PYPROJECT_TOOLS}
            if "format" in _dict(tool.get("ruff")):
                kinds.add("format")
        elif name in ("setup.cfg", "tox.ini"):
            for section in re.findall(r"^\[([^\]]+)\]", tree.text(rel) or "", re.MULTILINE):
                kinds |= {kind for regex, kind in INI_SECTIONS if regex.match(section.strip())}
        elif name == "package.json":
            data = _dict(_load("json", tree.text(rel)))
            kinds = {kind for key, kind in PACKAGE_JSON_KEYS.items() if key in data}
        elif name in ("pom.xml", "build.gradle", "build.gradle.kts"):
            text = tree.text(rel) or ""
            if "spotless" in text:
                kinds.add("format")
            if "checkstyle" in text:
                kinds.add("lint")
        out |= {(kind, tree.ws(rel)) for kind in kinds}
    return out


def _tests(tree: _Tree) -> tuple[Counter, set[str]]:
    dirs: Counter = Counter()
    patterns: set[str] = set()
    for rel in tree.files:
        if not _language(rel):
            continue  # docs, data and fixtures do not make a directory a test directory
        parts = _test_dirs(rel)  # src/main/... is production code even in a package named test
        in_root = False
        for index, part in enumerate(parts):
            if _test_root(part):
                dirs[tree.ws("/".join(parts[: index + 1]))] += 1
                in_root = True
                break
        pattern = _test_pattern(_name(rel), in_root)
        if pattern:
            patterns.add(pattern)
    return dirs, patterns


_NOT_TEST_CODE = {".sql", ".sh", ".bash", ".ps1"}  # fixtures and helper scripts


def _test_pattern(name: str, in_test_root: bool) -> str | None:
    """The test naming convention of a code file (``_test_name``), or ``Test*`` for a
    ``TestFoo`` file inside a test root; none for .sql and shell files."""
    suffix = PurePosixPath(name).suffix
    if suffix.lower() not in LANGUAGES or suffix.lower() in _NOT_TEST_CODE:
        return None
    if in_test_root and re.match(r"Test[A-Z][a-z]", name):
        return f"Test*{suffix}"
    return _test_name(name)


_DOC_STEMS = {"README", "CONTRIBUTING", "CHANGELOG", "ARCHITECTURE", "CONTEXT", "GLOSSARY",
              "TERMS", "DESIGN"}
